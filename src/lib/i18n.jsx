const LanguageContext = createContext();

export function LanguageProvider({ children }) {
  const [lang, setLang] = useState(() => localStorage.getItem("lang") || "so");

  useEffect(() => {
    localStorage.setItem("lang", lang);
    const dir = lang === "ar" ? "rtl" : "ltr";
    document.documentElement.dir = dir;
    document.documentElement.lang = lang;
  }, [lang]);

  const t = (key, params) => {
    let str = translations[lang]?.[key] ?? translations.so[key] ?? key;
    if (params) {
      Object.entries(params).forEach(([k, v]) => {
        str = str.replace(`{${k}}`, v);
      });
    }
    return str;
  };

  return (
    <LanguageContext.Provider value={{ lang, setLang, t, dir: lang === "ar" ? "rtl" : "ltr" }}>
      {children}
    </LanguageContext.Provider>
  );
}

export const useT = () => {
  const ctx = useContext(LanguageContext);
  // Defensive fallback: if a component renders outside the provider (e.g. during
  // hot-reload or an edge mount), return a safe default instead of crashing.
  if (!ctx) {
    return {
      lang: "so",
      setLang: () => {},
      t: (key) => key,
      dir: "ltr",
    };
  }
  return ctx;
};